// Bundles src/player/injected-entry.ts into a self-contained IIFE and writes
// it as a string constant to src/generated/injected-script.ts, so the mobile
// app can inject it without any bundler step of its own.
//
//   node scripts/build-injected.mjs          regenerate
//   node scripts/build-injected.mjs --check  fail if the committed file is stale
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/generated/injected-script.ts');

const result = await build({
  entryPoints: [resolve(root, 'src/player/injected-entry.ts')],
  bundle: true,
  format: 'iife',
  // Syntax-level target: Android System WebView 73+ and iOS 12.2+ WKWebView.
  // (A browser-version target trips esbuild's known Chrome 80 destructuring bug.)
  target: ['es2019'],
  minify: true,
  legalComments: 'none',
  write: false,
  platform: 'browser',
});

const code = result.outputFiles[0].text.trim();
const hash = createHash('sha256').update(code).digest('hex').slice(0, 16);
const contents = `// GENERATED by scripts/build-injected.mjs from src/player/injected-entry.ts.
// Do not edit by hand; run \`npm run build -w @watch-party/shared\`.
/* eslint-disable */
export const INJECTED_PLAYER_SCRIPT_HASH = '${hash}';
export const INJECTED_PLAYER_SCRIPT: string = ${JSON.stringify(code)};
`;

if (process.argv.includes('--check')) {
  const current = await readFile(outFile, 'utf8').catch(() => '');
  if (current !== contents) {
    console.error(
      'src/generated/injected-script.ts is stale. Run: npm run build -w @watch-party/shared',
    );
    process.exit(1);
  }
  console.log(`injected script up to date (${hash}, ${code.length} bytes)`);
} else {
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, contents);
  console.log(`wrote injected script (${hash}, ${code.length} bytes)`);
}
